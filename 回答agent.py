# -*- coding: utf-8 -*-
"""③ 回答 agent：拿着资料和病历，把话写出来。

职责：组装 prompt（守则 + 资料 + 病历 + 问题）→ 生成草稿。
      被审核驳回时，带上"上一版哪里不对"再写一遍。

这个 agent 是整条流水线里**唯一写话的**。
分诊只判风险、检索只取段、审核只挑错，都不写话。
这就是职责分离：写话的人不负责检查自己，检查的人不负责写话——
自己检查自己等于没检查。
"""

import 提示词
from llm import 调AI


def 回答(状态, 重写问题=None):
    """生成（或重写）草稿，同时写回 状态["草稿"]。

    重写问题：审核 agent 挑出来的问题清单。
              None = 第一版；有值 = 带着问题清单重写。
    """
    资料 = "\n".join(状态["检索段落"])
    用户消息 = 提示词.患者问句(资料, 状态["病历"], 状态["问题"])

    if 重写问题:
        用户消息 += 提示词.重写指令模板.format(
            问题列表="\n".join("· " + 条 for 条 in 重写问题)
        )

    消息 = [
        {"role": "system", "content": 提示词.患者守则},
        {"role": "user", "content": 用户消息},
    ]

    try:
        草稿 = 调AI(消息, 超时=120).get("content") or ""
    except Exception as e:
        # 这一步挂了不能让整条流水线炸掉（py41.py 的 /问经方 原来有 try 兜底，
        # 新版第一稿把这个丢了——一次网络抖动，患者连劝医话术都拿不到）。
        # 这里退化成空草稿，交给审核 → 驳回 → 重写 → 还不行就降级成安全话术。
        # 患者至少拿到一句人话，不是 500。
        print("回答 agent 调用失败，交给审核层处理：", repr(e))
        草稿 = ""

    状态["草稿"] = 草稿
    return 草稿
