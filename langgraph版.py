# -*- coding: utf-8 -*-
"""LangGraph 重写版：同样一条流水线，换成图来搭。

和 编排.py（手写版）是**同一条流水线、同样的四个 agent**，
区别只在"谁负责调度"：

    手写版：一个 while 循环 + 两个 if，你自己管顺序和回边
    LangGraph：把每一步声明成一个节点，把分支声明成条件边，图自己跑

为什么要两个版本都留着：
    面试被问"多 agent 怎么调度"，你能拿手写版指着代码讲清楚机制；
    被问"为什么不用框架"，你能拿这版说明你知道框架替你做了什么——
    状态合并、条件路由、循环收敛，这些 LangGraph 都替你办了。
    两个版本做对拍（见 __main__），是"我两种都实现过并验证过等价"的证据。

对应关系一目了然：

    手写版                           LangGraph 版
    ─────────────────────────────    ─────────────────────────────
    状态 dict                        StateGraph 的 state schema
    函数调用 + 返回值                add_node（节点返回要更新的字段）
    if 分诊agent.该劝医(等级)        add_conditional_edges（分诊后去哪）
    while True 里的重写计数          add_conditional_edges（审核后去哪）
    循环回边                          add_edge("记重写", "回答")
    return 状态                      graph.invoke(初始状态)

一个必须知道的差别：**状态合并语义**。
    LangGraph 默认把节点返回的字段**覆盖**到状态上。
    所以"轨迹"这种要**累加**的字段，得用 Annotated[list, operator.add]
    声明一个 reducer，否则每次都会被后来者盖掉——
    手写版里是直接 append，不需要想这件事。
"""

import operator
import os
import sys
import time
from typing import Annotated, TypedDict

_本目录 = os.path.dirname(os.path.abspath(__file__))
if _本目录 not in sys.path:
    sys.path.insert(0, _本目录)

from langgraph.graph import END, START, StateGraph

import 分诊agent, 检索agent, 回答agent, 审核agent, 规则
from 编排 import 最多重写次数


class 图状态(TypedDict):
    # —— 输入 ——
    问题: str
    顾客: str
    病历: str
    段落库: list
    用模型分诊: bool

    # —— 各步产出 ——
    风险等级: str
    风险理由: str
    检索段落: list
    草稿: str
    审核结论: str
    审核问题: list
    重写次数: int
    最终回答: str

    # 轨迹要**累加**，所以声明一个加法 reducer。
    # 不写这条，每个节点返回的轨迹都会把前面的盖掉，最后只剩一条。
    轨迹: Annotated[list, operator.add]


def _计时条(步骤, 开始, 备注):
    """造一条轨迹记录（和 状态.py 的 记轨迹 格式一致）。"""
    return {
        "步骤": 步骤,
        "耗时毫秒": round((time.perf_counter() - 开始) * 1000, 1),
        "备注": 备注,
    }


# —————————— 节点 ——————————

def 分诊节点(状态):
    开始 = time.perf_counter()
    等级, 理由, 命中 = 分诊agent.分诊(状态["问题"], 用模型兜底=状态["用模型分诊"])
    return {
        "风险等级": 等级,
        "风险理由": 理由,
        "轨迹": [_计时条("分诊", 开始, f"{等级}｜{理由}")],
    }


def 劝医节点(状态):
    开始 = time.perf_counter()
    return {
        "最终回答": 规则.劝医话术.get(状态["风险等级"], 规则.劝医话术["危险信号"]),
        "轨迹": [_计时条("劝医", 开始, "命中风险，跳过检索与回答")],
    }


def 检索节点(状态):
    开始 = time.perf_counter()
    库 = 状态.get("段落库") or []
    if 库:
        段落 = 检索agent.检索(状态["问题"], 库)
        备注 = f"取回 {len(段落)} 段"
    else:
        段落 = []
        备注 = "无知识库，跳过"
    return {
        "检索段落": 段落,
        "轨迹": [_计时条("检索", 开始, 备注)],
    }


def 回答节点(状态):
    开始 = time.perf_counter()
    # agent 函数是就地把结果写进状态 dict 的，
    # 这里传一份副本进去，再把它写好的字段取出来返回 —— 符合 LangGraph 的范式。
    工作 = dict(状态)
    重写问题 = 工作["审核问题"] if 工作["重写次数"] > 0 else None
    回答agent.回答(工作, 重写问题)
    备注 = "初稿" if 工作["重写次数"] == 0 else f"第 {工作['重写次数']} 次重写"
    return {
        "草稿": 工作["草稿"],
        "轨迹": [_计时条("回答", 开始, 备注)],
    }


def 审核节点(状态):
    开始 = time.perf_counter()
    结论, 问题列表 = 审核agent.审核(dict(状态))
    备注 = 结论 + ("：" + "；".join(问题列表) if 问题列表 else "")
    return {
        "审核结论": 结论,
        "审核问题": 问题列表,
        "轨迹": [_计时条("审核", 开始, 备注)],
    }


def 定稿节点(状态):
    return {"最终回答": 状态["草稿"]}


def 记重写节点(状态):
    return {
        "重写次数": 状态["重写次数"] + 1,
        "草稿": "",
    }


def 降级节点(状态):
    开始 = time.perf_counter()
    return {
        "最终回答": 审核agent.安全话术(),
        "轨迹": [_计时条("降级", 开始, f"重写 {最多重写次数} 次仍未过")],
    }


# —————————— 路由（手写版里的那两个 if）——————————

def 分诊后去哪(状态):
    return "劝医" if 分诊agent.该劝医(状态["风险等级"]) else "检索"


def 审核后去哪(状态):
    if 状态["审核结论"] == "通过":
        return "定稿"
    if 状态["重写次数"] < 最多重写次数:
        return "重写"
    return "降级"


# —————————— 搭图 ——————————

def 建图():
    建造 = StateGraph(图状态)

    建造.add_node("分诊", 分诊节点)
    建造.add_node("劝医", 劝医节点)
    建造.add_node("检索", 检索节点)
    建造.add_node("回答", 回答节点)
    建造.add_node("审核", 审核节点)
    建造.add_node("定稿", 定稿节点)
    建造.add_node("记重写", 记重写节点)
    建造.add_node("降级", 降级节点)

    建造.add_edge(START, "分诊")
    建造.add_conditional_edges("分诊", 分诊后去哪, {"劝医": "劝医", "检索": "检索"})
    建造.add_edge("检索", "回答")
    建造.add_edge("回答", "审核")
    建造.add_conditional_edges(
        "审核", 审核后去哪, {"定稿": "定稿", "重写": "记重写", "降级": "降级"}
    )
    建造.add_edge("记重写", "回答")      # 回边：重写完再走一遍回答→审核
    建造.add_edge("定稿", END)
    建造.add_edge("劝医", END)
    建造.add_edge("降级", END)

    return 建造.compile()


# 编译一次就够了，别每次调用都重编译
_图 = None


def 跑图(问题, 顾客="", 段落库=None, 病历="", 用模型分诊=True):
    """LangGraph 版入口，签名和 编排.跑流水线 保持一致，方便对拍。"""
    global _图
    if _图 is None:
        _图 = 建图()

    结果 = _图.invoke({
        "问题": 问题,
        "顾客": 顾客,
        "病历": 病历,
        "段落库": 段落库 or [],
        "用模型分诊": 用模型分诊,
        "风险等级": "正常",
        "风险理由": "",
        "检索段落": [],
        "草稿": "",
        "审核结论": "",
        "审核问题": [],
        "重写次数": 0,
        "最终回答": "",
        "轨迹": [],
    })
    return 结果


# —————————— 对拍 ——————————

if __name__ == "__main__":
    from importlib.metadata import version as _取版本

    from 编排 import 跑流水线

    测试库 = [
        "痛经的日常养护：注意腹部保暖，经期避免生冷和剧烈运动，规律作息，情绪保持平稳。",
    ]

    用例 = [
        ("急症（走劝医分支）", "医生我突然胸痛", False),
        ("正常咨询（走完整链路）", "我每次来月经肚子都疼，平时要注意什么", False),
        ("方名陷阱（可能触发重写）", "桂枝汤怎么煎？一天喝几次？", True),
    ]

    print("=" * 70)
    print(f"手写版 vs LangGraph 版 · 对拍（langgraph {_取版本('langgraph')}）")
    print("=" * 70)

    全部一致 = True
    for 名称, 问题, 用模型分诊 in 用例:
        print(f"\n【{名称}】{问题}")

        手写 = 跑流水线(问题, 顾客="对拍", 段落库=测试库, 用模型分诊=用模型分诊)
        图 = 跑图(问题, 顾客="对拍", 段落库=测试库, 用模型分诊=用模型分诊)

        比 = [
            ("风险等级", 手写["风险等级"], 图["风险等级"]),
            ("审核结论", 手写["审核结论"], 图["审核结论"]),
            ("重写次数", 手写["重写次数"], 图["重写次数"]),
            ("是否劝医", 手写["风险等级"] != "正常", 图["风险等级"] != "正常"),
        ]

        for 字段, 左, 右 in 比:
            一致 = 左 == 右
            全部一致 = 全部一致 and 一致
            print(f"   {'✓' if 一致 else '✗'} {字段:<10} 手写={左!r:<12} 图={右!r}")

        # 最终回答不要求逐字相同（模型有随机性），
        # 但两条链的红线结论必须一致：都不许出现方剂名。
        手写方名 = 规则.查方名(手写["最终回答"])
        图方名 = 规则.查方名(图["最终回答"])
        红线一致 = (not 手写方名) and (not 图方名)
        全部一致 = 全部一致 and 红线一致
        print(f"   {'✓' if 红线一致 else '✗'} 红线检查   手写={手写方名 or '无方名'}  图={图方名 or '无方名'}")

        print(f"   手写轨迹 {len(手写['轨迹'])} 步 / 图轨迹 {len(图['轨迹'])} 步")

    print()
    print("=" * 70)
    print("对拍结论：" + ("两条链行为一致 ✓" if 全部一致 else "存在不一致 ✗"))
    print("=" * 70)
