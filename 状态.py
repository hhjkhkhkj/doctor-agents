# -*- coding: utf-8 -*-
"""流水线状态：agent 之间只传这个结构，不传拼好的字符串。

为什么要专门定义一个状态？
  改动之前，py41.py 里各步骤靠"拼字符串"传递——资料拼进 prompt、
  病历拼进 prompt，拼完就丢了，谁也说不清中间到底发生了什么。

  改成结构化的状态后：
    ① 每个 agent 的输入输出都是明确字段，能单独测（喂假状态进去，看字段对不对）
    ② 轨迹字段记下每步耗时，能一眼看出慢在哪一步
    ③ 出问题时能打印完整状态，不用猜

  这就是"多 agent 系统"和"一坨函数"的区别之一：agent 之间有契约。
"""

from typing import TypedDict


class 流水线状态(TypedDict):
    # —— 输入 ——
    问题: str
    顾客: str

    # —— 分诊 agent 产出 ——
    病历: str
    风险等级: str        # 正常 / 危险信号 / 急症
    风险理由: str

    # —— 检索 agent 产出 ——
    检索段落: list

    # —— 回答 agent 产出 ——
    草稿: str

    # —— 审核 agent 产出 ——
    审核结论: str        # 通过 / 驳回
    审核问题: list
    重写次数: int

    # —— 最终产出 ——
    最终回答: str
    轨迹: list           # 每步一条：{步骤, 耗时毫秒, 备注}


def 新状态(问题: str, 顾客: str) -> 流水线状态:
    """造一个初始状态。

    所有字段都先填好默认值，后面任何 agent 直接读字段就行，
    不会因为"某个 agent 没走到、字段不存在"而 KeyError。
    """
    return {
        "问题": 问题,
        "顾客": 顾客,
        "病历": "",
        "风险等级": "正常",
        "风险理由": "",
        "检索段落": [],
        "草稿": "",
        "审核结论": "",
        "审核问题": [],
        "重写次数": 0,
        "最终回答": "",
        "轨迹": [],
    }


def 记轨迹(状态: 流水线状态, 步骤: str, 耗时毫秒: float, 备注: str = "") -> None:
    """往状态里追加一条轨迹。每步做完都调一次，就得到完整的执行链路。"""
    状态["轨迹"].append({"步骤": 步骤, "耗时毫秒": round(耗时毫秒, 1), "备注": 备注})


def 打印轨迹(状态: 流水线状态) -> None:
    """把轨迹打成人能看的表——调试和演示都用它。"""
    总耗时 = sum(条["耗时毫秒"] for 条 in 状态["轨迹"])
    print("-" * 56)
    print("执行轨迹")
    print("-" * 56)
    for 条 in 状态["轨迹"]:
        print(f"  {条['步骤']:<12} {条['耗时毫秒']:>8.1f} ms   {条['备注']}")
    print("-" * 56)
    print(f"  {'合计':<12} {总耗时:>8.1f} ms")
