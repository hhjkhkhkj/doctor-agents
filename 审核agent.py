# -*- coding: utf-8 -*-
"""④ 审核 agent：查草稿有没有踩红线。整条流水线的安全阀。

两层检查：
  规则层（确定性，先跑，不花钱）——方名、免责声明、急症话术
  模型层（语义兜底）——"变相给了具体用药方案"这种规则抓不到的

为什么两层都要：
  规则层负责"库里有写的、清单里列过的一律不漏"，但它只认字面；
  模型层能听懂"你可以去药店抓点柴胡桂枝煮水喝"这种绕开的说法，但它会飘。

  ⚠️ 别把规则层说成"绝对不会漏"——第一版 README 就是这么吹的，
     实际它只覆盖 40 个经方名，连"六味地黄丸"都拦不住（独立审查实测）。
     正确的说法：**两层各有各的漏，叠起来才够用。**

驳回不是终点：
  带上问题清单回到回答 agent 重写，最多重写 2 次；
  次数用完还是不通过 → 降级成安全话术（宁可答不好，不可答错）。
"""

import 规则
from llm import 调AI


# —————— 模型路由 ——————
# 哪一步用哪个模型，是一个明确的决定，不是随手写死。
#
# 审核为什么走便宜的 flash：
#   ① 实测它原来比回答还贵——0.90 分 vs 0.61 分
#   ② 贵的原因是"思考"：530 个输出 token 里 528 个是 reasoning
#   ③ 但它的活其实更简单——回答是"写一段话"，审核只是"挑错"
#   ④ 而且它下面还有一层确定性规则兜着（规则层不花模型钱）
#
# ⚠️ 换模型是有风险的。改完必须跑 评测/跑评测.py 验证红线没退。
#    这就是评测集存在的意义：它让你敢改。
审核用模型 = "deepseek-flash"


审核提示 = (
    "你是医疗回复的合规审核员，只挑错，不改写。\n"
    "下面这条回复是给患者的，检查它有没有违反下面任意一条：\n"
    "1) 出现了任何中药方剂名、药方、具体剂量（包括变相的说法，"
    "比如'抓点柴胡桂枝煮水'）\n"
    "2) 涉及调理用药，却没有免责声明\n"
    "3) 患者情况属于急症或需要就医，回复却没有劝其就医\n"
    "如果没问题，只输出两个字：通过\n"
    "如果有问题，每行列一条问题，不要多说别的，不要复述原文。"
)

# 出现这些词，说明这条回复"涉及调理用药"，按守则第 3 条必须带免责声明。
#
# 不用"吃/喝"这种太宽的字——"多喝热水"不该被要求免责。
# 也刻意不收单字"泡"："睡前温水泡脚有好处"会被误判成用药建议，
# 于是正常回答被反复驳回。收"药浴""外敷"这种确实指用药的说法。
涉及调理词 = ("调理", "服用", "用药", "外敷", "艾灸", "食疗", "煎服", "药浴")


def 需要免责(草稿):
    """这条回复算不算"涉及调理用药"，需要带免责声明。"""
    return any(词 in (草稿 or "") for 词 in 涉及调理词)


def 劝医了吗(草稿):
    """草稿里有没有劝就医的意思。"""
    return any(词 in (草稿 or "") for 词 in ("就医", "医院", "联系医生", "面诊"))


def 审核(状态):
    """审核 状态["草稿"]，返回 (结论, 问题列表)。结论是 "通过" 或 "驳回"。"""
    草稿 = 状态["草稿"] or ""
    问题 = []

    # —————————— 零层：空草稿 ——————————
    # 空草稿对"不含方剂名"这类否定式检查是天然"干净"的。
    # 不先拦掉的话会判通过，患者就收到一条空回复。
    if not 草稿.strip():
        return "驳回", ["草稿是空的，没有能发给患者的内容"]

    # —————————— 规则层 ——————————
    命中方名 = 规则.查方名(草稿)
    if 命中方名:
        问题.append("出现了方剂名：" + 规则.用逗号分开(命中方名))

    if 需要免责(草稿) and not 规则.含免责(草稿):
        问题.append("涉及调理建议，但没带免责声明（缺'仅供参考'）")

    # 这条是冗余保险：正常情况下风险等级非"正常"时，编排层早就短路去劝医了，
    # 根本走不到审核。留着是为了万一将来编排逻辑改了，这道检查还在。
    if 状态["风险等级"] != "正常" and not 劝医了吗(草稿):
        问题.append("情况需要就医，但回复没有劝患者就医")

    # 规则层已经挑出问题 → 直接驳回，不必再花钱问模型
    if 问题:
        return "驳回", 问题

    # —————————— 模型层（语义兜底）——————————
    # 这一层是 **fail-closed** 的：模型挂了、返回空、返回看不懂的东西，
    # 一律按驳回处理，绝不放行。
    #
    #   第一版写成了 fail-open——模型一失败就 return "通过"，
    #   等于把最该守的那道门交给了最不稳定的那个环节。
    #   这是独立审查实测出来的：草稿"你可以自己去药店抓点柴胡桂枝煮水喝"
    #   在"抛异常 / 返回空 / 返回 None"三种情况下全部被放行给了患者。
    #
    #   代价要说清楚：审核模型如果长时间挂掉，所有消息都会走重写→降级，
    #   患者拿到的是"答不好，已记录请医生解答"。这比漏一条红线出去好。
    try:
        原始 = 调AI([
            {"role": "system", "content": 审核提示},
            {"role": "user", "content": "【患者问题】" + 状态["问题"] +
                                       "\n\n【待审回复】" + 草稿},
        ], 超时=60, 模型=审核用模型).get("content")
    except Exception as e:
        return "驳回", ["审核模型调用失败，未能完成语义检查：" + repr(e)]

    判定 = (原始 or "").strip()
    if not 判定:
        return "驳回", ["审核模型没有返回判定，未能完成语义检查"]

    if 判定.startswith("通过"):
        return "通过", []

    条 = [行.strip(" -·•*　\t") for 行 in 判定.splitlines() if 行.strip()]
    return "驳回", 条 or ["模型审核未通过"]


def 安全话术():
    """重写次数用尽还是不过时的兜底回复。宁可答不好，不可答错。"""
    return ("这个问题我这边暂时答不好，为了不给你错误信息，就不硬答了。"
            "已经记录下来，会请张医生为您解答。")
