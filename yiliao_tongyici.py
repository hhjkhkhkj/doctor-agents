def 展开同义词(问题):
    """把问题里的别名换成标准词，追加到问题后面，让向量检索更准。
    例：'我血压高怎么办' → '我血压高怎么办 高血压'
    """
    补充词 = []
    for 标准词, 别名们 in 同义词表.items():
        if 标准词 in 问题:
            continue          # 已经用了标准说法，不用补
        for 别名 in 别名们:
            if 别名 in 问题:
                补充词.append(标准词)
                break         # 找到一条别名就够了
    if not 补充词:
        return 问题
    return 问题 + " " + " ".join(补充词)


