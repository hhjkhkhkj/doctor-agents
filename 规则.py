危险信号规则 = [
    ("同房出血", r"同房.{0,8}(出血|见红|血)"),
    ("持续小腹剧痛", r"(小腹|下腹|肚子).{0,10}(剧痛|疼得厉害|疼得直不起腰|痛得厉害)"),
    ("发热", r"发热|发烧|低烧|高烧"),
    ("大量异常出血", r"(大量|异常).{0,4}出血"),
    ("不规则出血", r"不规则出血|淋漓不尽"),
    ("HPV高危阳性", r"HPV\s*(16|18)|HPV\s*高危"),
    ("TCT异常", r"TCT|宫颈细胞学"),
    ("异常分泌物", r"(异常|大量).{0,4}分泌物"),
]


def _扫(规则表, 文本):
    """按规则表扫一遍，返回命中的名字列表。"""
    命中 = []
    for 名字, 模式 in 规则表:
        if re.search(模式, 文本, re.IGNORECASE):
            命中.append(名字)
    return 命中


def 查风险(文本):
    """按规则判风险等级，返回 (等级, 命中的名字列表)。

    等级：急症 > 危险信号 > 正常。

    这段是纯规则、不看模型——急症判定必须是确定性的，
    不能今天答对明天答错。规则没命中的交给 LLM 兜底（见 分诊agent.py）。
    """
    if not 文本:
        return "正常", []

    急中 = _扫(急症规则, 文本)
    if 急中:
        return "急症", 急中

    信中 = _扫(危险信号规则, 文本)
    if 信中:
        return "危险信号", 信中

    return "正常", []


# ============ ③ 免责声明 ============

# 守则第 3 条要求的那句话。但回答 agent 不一定逐字照念——
# 实测"以医生面诊为准，请遵医嘱"这种完全合规的说法会被判成"缺免责声明"，
# 于是正常回答被反复驳回、甚至降到安全话术。
# 认几种等价说法，别死抠字面。
免责说法 = ("仅供参考", "以医生面诊为准", "请遵医嘱", "面诊后使用", "四诊合参")


def 含免责(文本):
    """回答里有没有免责声明。守则第 3 条：涉及调理用药时必须带。"""
    文本 = 文本 or ""
    return any(说法 in 文本 for 说法 in 免责说法)


