# ============ ① 方剂名（患者端禁用词）============

def 提取方名():
    """从经方库里把所有方剂名抓出来，当作患者端的"禁用词"清单。

    为什么不手抄一份清单：库更新了（加了新方）清单自动跟上，
    不会出现"库里补了方、检查表忘了补"这种漏洞。

    后缀只取 汤/丸/散 —— 经方的三大剂型，覆盖了本库全部真方名。
    （早先连带收了 饮/煎/膏/丹，结果把"口渴喜冷饮""大渴饮"这类
    描述性短语也当成方名抓了进来，会误伤正常回答。如果以后库里
    真补进"饮"类方，比如香薷饮，把"饮"加回下面的后缀表即可。）

    首字是连接词的（"四逆汤合乌梅丸"里连出来的"合乌梅丸"）不是方名，
    剔掉——真方名"乌梅丸"本身在库里别处出现过，抓得到。
    """
    词 = set()
    连接词 = "合或和及与用加配同"
    干扰字 = "不者忌宜"          # "汗者不用桂枝汤"这种句子片段，不是方名
    # 上限放到 10 个汉字：原来卡在 6 字，把"茯苓桂枝白术甘草汤"
    # "桂枝二越婢一汤"这类真经方整个漏掉了（独立审查实测出来的）。
    # 放宽会引进噪音，靠下面两道过滤兜。
    for 段 in 经方知识:
        for 命中 in re.findall(r"[一-龥]{2,10}?(?:汤|丸|散)", 段):
            if 命中[0] in 连接词:
                continue
            if any(字 in 命中 for 字 in 干扰字):
                continue
            词.add(命中)
    return 词


