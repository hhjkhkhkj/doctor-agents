"""手写编排器：把四个 agent 串成一条流水线。

为什么先手写、不直接上 LangGraph：
  这套调度逻辑一共就几十行——一个 while 加两个 if。
  手写的好处是每一步都在眼皮底下，出问题知道去哪看；
  面试被问"多 agent 怎么调度的"，你能指着这几行讲清楚。
  等它跑通、评测过了，再用 LangGraph 重写一遍做对比（见 langgraph版.py）。

流水线走法：
  分诊 ──急症/危险信号──▶ 直接劝医，结束
       └──正常──▶ 检索 ──▶ 回答 ⇄ 审核（不过就打回重写，最多 2 次）
                             └──重写用完还不过──▶ 降级成安全话术
"""

import time

if __package__:
    # 正常情况：作为包被导入（from 编排 import 跑流水线）
    import 分诊agent, 检索agent, 回答agent, 审核agent, 规则
    from 状态 import 新状态, 记轨迹, 打印轨迹
else:
    # 直接跑这个文件时（py 编排.py）没有包上下文，改成绝对导入
    import os as _os
