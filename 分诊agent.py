# -*- coding: utf-8 -*-
"""① 分诊 agent：先判风险，再决定后面还要不要跑。

职责：拿患者的问题，判它是"正常咨询"还是"急症/危险信号"。
      判成急症或危险信号，后面的检索、回答、审核全部不跑，
      直接返回劝医话术——这是最省时间也最安全的路径。

为什么规则在前、模型在后：
  · 急症判定必须是确定性的，不能今天答对明天答错
  · 规则命中就省掉一次模型调用（快、省钱）
  · 规则只会认字面，换个说法就漏——那部分交给模型兜底
"""

import re

import 规则
from llm import 调AI


# 分诊的模型兜底也走便宜的 flash——它只是判断"急症/危险信号/正常"，
# 是个很轻的分类任务，不需要 pro。而规则已经先挡了一道。
分诊用模型 = "deepseek-flash"


分诊提示 = (
    "你是医疗分诊员。读患者这句话，判断急迫程度，只输出一个词。\n"
    "可选：急症 / 危险信号 / 正常\n"
    "急症 = 需要立刻就医（大出血、晕倒、胸痛、呼吸困难、孕期出血等）\n"
    "危险信号 = 需要尽快线下就医（同房出血、持续腹痛、发热、异常出血、"
    "HPV高危阳性、TCT异常、异常分泌物等）\n"
    "正常 = 一般咨询，可以居家调理观察\n"
    "只输出那一个词，不要解释，不要标点。"
)


def 分诊(问题, 用模型兜底=True):
    """返回 (风险等级, 理由, 命中的词)。

    风险等级：急症 / 危险信号 / 正常。
    """
    # —— 第一层：规则。命中就直接定，不碰模型 ——
    等级, 命中 = 规则.查风险(问题)
    if 等级 != "正常":
        return 等级, "规则命中：" + 规则.用逗号分开(命中), 命中

    # —— 第二层：模型兜底（规则没命中，但患者可能换了说法）——
    if not 用模型兜底:
        return "正常", "规则未命中，未启用模型兜底", []

    try:
        回答 = 调AI([
            {"role": "system", "content": 分诊提示},
            {"role": "user", "content": 问题},
        ], 超时=30, 模型=分诊用模型).get("content")
    except Exception as e:
        # 兜底失败不把患者卡住——按"正常"往下走，由后面的审核层再兜一道
        print("分诊模型兜底失败，按正常处理：", repr(e))
        return "正常", "分诊模型调用失败，规则未命中", []

    # 只留汉字，好让"急症。""急症 "这类带标点/空格的回答也能对上
    判断 = re.sub(r"[^一-龥]", "", 回答 or "")

    # 第一优先：精确等于某个选项（模型照要求只吐一个词，这是常态）
    if 判断 in ("急症", "危险信号", "正常"):
        return 判断, "模型判断：" + 判断, []

    # 没给标准答案，退一步看包含关系。
    # 顺序讲究：先"危险信号"再"急症"——方向取更安全的那一侧，
    # 宁可多劝一次医，也不能把该就医的降成"正常"。
    #
    #   第一版是按 (急症, 危险信号, 正常) 顺序取首个命中的子串，
    #   实测有两个毛病：
    #     · "这不是急症，是危险信号" → 判成"急症"（方向安全但判错）
    #     · "需要尽快就医""风险较高" → 一个关键词都没命中，直接落到"正常"
    #   第二种才是真正危险的：模型明明表达了要就医，却被降级成居家调理。
    for 候选 in ("危险信号", "急症"):
        if 候选 in 判断:
            return 候选, "模型判断（含'%s'）：%s" % (候选, 判断[:20]), []

    return "正常", "模型未给出明确判断：" + (判断[:20] or "空")


def 该劝医(等级):
    """这个等级要不要直接劝医（不走回答 agent）。"""
    return 等级 in ("急症", "危险信号")
